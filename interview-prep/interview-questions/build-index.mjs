import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = import.meta.dirname;
const tracks = [
  ["React", "react"],
  ["NestJS", "nestjs"],
  ["Node.js", "nodejs"],
  ["Databases", "databases"],
];
const idRe = /^###\s+((?:REACT|NEST|NODE|DB)-\d+)\s+—\s+(.+)$/gm;

let body = `# Index

Generated by \`build-index.mjs\`. Only files that exist are listed. The full 40-file plan and remaining counts are in [PROGRESS.md](./PROGRESS.md). Re-run the script after adding questions.

`;

for (const [title, dirName] of tracks) {
  body += `## ${title}\n\n`;
  const dir = join(root, dirName);
  const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
  if (!files.length) {
    body += "_No topic files yet._\n\n";
    continue;
  }
  for (const name of files) {
    const text = readFileSync(join(dir, name), "utf8");
    const found = [...text.matchAll(idRe)];
    body += `### [${name}](./${dirName}/${name}) (${found.length})\n\n`;
    for (const m of found) {
      const slug = m[1].toLowerCase();
      body += `- [${m[1]}](./${dirName}/${name}#${slug}) — ${m[2].trim()}\n`;
    }
    body += "\n";
  }
}

writeFileSync(join(root, "INDEX.md"), body);
console.log("wrote INDEX.md");
